using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace ToolBX.AssemblyInitializer.Generators;

/// <summary>
/// Discovers <c>IAssemblyInitializer</c> implementations at compile time and emits a registrar that instantiates
/// them with ordinary <c>new</c> expressions, plus an assembly-level marker attribute. This replaces runtime
/// assembly scanning + <c>Activator.CreateInstance</c>, which the trimmer/NativeAOT cannot statically reason about.
/// </summary>
[Generator]
public sealed class AssemblyInitializerSourceGenerator : IIncrementalGenerator
{
    private const string InterfaceName = "ToolBX.AssemblyInitializer.IAssemblyInitializer";

    private static readonly DiagnosticDescriptor MissingConstructor = new(
        id: "AINIT001",
        title: "Initializer needs a public parameterless constructor",
        messageFormat: "'{0}' implements IAssemblyInitializer but has no public parameterless constructor and cannot be instantiated",
        category: "AssemblyInitializer",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax { BaseList.Types.Count: > 0 },
                transform: static (ctx, _) => GetCandidate(ctx))
            .Where(static candidate => candidate is not null)
            .Select(static (candidate, _) => candidate!.Value);

        context.RegisterSourceOutput(candidates.Collect(), static (spc, items) => Execute(spc, items));
    }

    private static Candidate? GetCandidate(GeneratorSyntaxContext context)
    {
        if (context.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)context.Node) is not INamedTypeSymbol symbol)
            return null;

        if (symbol.IsAbstract || symbol.TypeKind != TypeKind.Class || symbol.IsGenericType)
            return null;

        if (!symbol.AllInterfaces.Any(static i => i.ToDisplayString() == InterfaceName))
            return null;

        var hasParameterlessConstructor = symbol.InstanceConstructors.Any(static c =>
            c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public);

        return new Candidate(
            symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            hasParameterlessConstructor,
            context.Node.GetLocation());
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<Candidate> candidates)
    {
        if (candidates.IsDefaultOrEmpty)
            return;

        var typeNames = new List<string>();
        foreach (var candidate in candidates)
        {
            if (!candidate.HasParameterlessConstructor)
            {
                context.ReportDiagnostic(Diagnostic.Create(MissingConstructor, candidate.Location, candidate.TypeName));
                continue;
            }

            typeNames.Add(candidate.TypeName);
        }

        var ordered = typeNames.Distinct().OrderBy(static name => name, StringComparer.Ordinal).ToList();
        if (ordered.Count == 0)
            return;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        builder.AppendLine();
        builder.AppendLine("[assembly: global::ToolBX.AssemblyInitializer.HasAssemblyInitializers]");
        builder.AppendLine();
        builder.AppendLine("namespace ToolBX.AssemblyInitializer.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    internal static class AssemblyInitializerRegistrar");
        builder.AppendLine("    {");
        builder.AppendLine("        public static global::System.Collections.Generic.IReadOnlyList<global::ToolBX.AssemblyInitializer.IAssemblyInitializer> CreateInitializers()");
        builder.AppendLine("        {");
        builder.AppendLine("            return new global::ToolBX.AssemblyInitializer.IAssemblyInitializer[]");
        builder.AppendLine("            {");
        foreach (var typeName in ordered)
            builder.AppendLine($"                new {typeName}(),");
        builder.AppendLine("            };");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("AssemblyInitializerRegistrar.g.cs", builder.ToString());
    }

    private readonly record struct Candidate(string TypeName, bool HasParameterlessConstructor, Location Location);
}
